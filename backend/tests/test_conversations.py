class FakeAIService(AIService):
    def __init__(self, reply: str = "Test assistant reply generated by the fake AI service."):
        self.reply = reply
        self.calls = 0
        self.fail_next = False

    async def generate_reply(self, *, system_prompt: str, history: list[ChatTurn]) -> str:
        self.calls += 1
        if self.fail_next:
            self.fail_next = False
            raise AIServiceError("Simulated AI provider failure.", status_code=502)
        if not history:
            raise AIServiceError("Empty history", status_code=400)
        return self.reply


